/// Draws renders that stayed on the GPU: registers their textures with the window's egui-wgpu
/// renderer (the GPU renderer runs on the window's device, see [`offer_window_device`]).
struct WindowTextures {
    device: eframe::wgpu::Device,
    queue: eframe::wgpu::Queue,
    renderer: std::sync::Arc<egui::mutex::RwLock<eframe::egui_wgpu::Renderer>>,
}

impl lcc_ui_egui::render::ScreenTextures for WindowTextures {
    fn show(&mut self, frame: &lcc_engine::media::ScreenFrame, id: Option<egui::TextureId>) -> Option<egui::TextureId> {
        let view = frame.texture.create_view(&Default::default());
        let mut r = self.renderer.write();
        let filter = eframe::wgpu::FilterMode::Linear;
        Some(match id {
            Some(id) => {
                r.update_egui_texture_from_wgpu_texture(&self.device, &view, filter, id);
                id
            }
            None => r.register_native_texture(&self.device, &view, filter),
        })
    }

    fn free(&mut self, id: egui::TextureId) {
        self.renderer.write().free_texture(&id);
    }

    fn read(&self, frame: &lcc_engine::media::ScreenFrame) -> Option<egui::ColorImage> {
        let img = lcc_engine::gpu::read_texture(&self.device, &self.queue, &frame.texture, frame.width, frame.height).ok()?;
        let pixels = img.data.iter().map(|p| egui::Color32::from_rgba_unmultiplied(p[0], p[1], p[2], p[3])).collect();
        Some(egui::ColorImage::new([img.width, img.height], pixels))
    }
}

/// Whether the window's HDR swapchain keeps the GPU renderer off the window's device: where it stopped
/// the window drawing (RADV on Wayland, 2026-11-03). Windows and macOS keep the zero-copy path on an
/// HDR monitor (ported from OneSlips: there it always offers the device).
const HDR_WINDOW_GUARD: bool = cfg!(not(any(windows, target_os = "macos", target_os = "android")));

/// Whether the GPU renderer is offered the window's device: `<PREFIX>_GPU_WINDOW` (`env`) `0` never,
/// `1` always; otherwise yes, except on an HDR window (`hdr`) where `guard` holds.
fn offers_window_device(env: Option<&str>, hdr: bool, guard: bool) -> bool {
    match env.map(str::trim) {
        Some("0") => false,
        Some("1") => true,
        _ => !(hdr && guard),
    }
}

/// Offer the window's device to the GPU renderer, so the loupe's drafts are drawn straight from the
/// GPU (the kernels are built on it when the renderer warms up, off the UI thread); the textures
/// they leave are shown through [`WindowTextures`] once it runs there. A device that doesn't suit
/// is declined and the renderer makes one of its own, as before: every render comes back as pixels.
fn offer_window_device(rs: &eframe::egui_wgpu::RenderState) -> WindowTextures {
    lcc_engine::gpu::offer_window_device(rs.device.clone(), rs.queue.clone(), &rs.adapter);
    WindowTextures { device: rs.device.clone(), queue: rs.queue.clone(), renderer: rs.renderer.clone() }
}

impl eframe::App for App {
    fn clear_color(&self, visuals: &egui::Visuals) -> [f32; 4] {
        // The transparency-capable window selects compositor presentation; the UI itself
        // stays opaque, including disabled panels beneath modal dimming. The theme's panel
        // colour, so a light theme doesn't flash black where nothing is drawn yet.
        let [r, g, b, _] = visuals.panel_fill.to_srgba_unmultiplied();
        egui::Color32::from_rgb(r, g, b).to_normalized_gamma_f32()
    }
    fn logic(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {
        #[cfg(target_os = "macos")]
        if let Some(m) = self.3.as_mut()
            && m.update(&mut self.0, ctx)
            && lcc_ui_egui::panels::notices::may_close(&mut self.0)
        {
            // Quit from the menu bar: save exactly what closing the window saves (settings and
            // library, after the unsaved-changes check; otherwise its prompt shows), then end the
            // process instead of closing the viewport while AppKit is terminating (PR #444).
            eframe::App::on_exit(self, None);
            std::process::exit(0);
        }
        self.0.logic(ctx);
        self.1.tick(&mut self.0, ctx);
    }
    fn raw_input_hook(&mut self, _ctx: &egui::Context, raw: &mut egui::RawInput) {
        self.0.raw_input_hook(raw);
    }
    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut eframe::Frame) {
        self.0.perf.host_frame_ms = frame.info().cpu_usage.map(|s| f64::from(s) * 1000.0);
        // the GPU renderer adopted the window's device: its renders can be drawn as they are
        if self.2.is_some()
            && lcc_engine::gpu::on_window_device()
            && let Some(t) = self.2.take()
        {
            self.0.renderer.set_screen_textures(Box::new(t));
        }
        self.0.ui(ui);
    }
    fn on_exit(&mut self, _gl: Option<&eframe::glow::Context>) {
        // (a size the window was just given is remembered too)
        self.0.ui.window = self.1.window_at_exit(self.0.ui.window);
        if let Err(e) = self.1.save(&self.0) {
            log::error!("{e}");
        }
        // Skip This Time in the quit prompt: no backup on this quit
        if self.0.exit_backup != Some(false) {
            catalog_hooks::backup_if_due(&mut self.0.session);
        }
        if let Err(e) = self.0.session.close_library() {
            log::error!("saving the catalog failed: {e}");
        }
        // last, with everything saved: no render may be inside the GPU driver when the process ends
        if !self.0.shutdown(EXIT_WAIT) {
            log::warn!("quit: background work was still running after {EXIT_WAIT:?}");
        }
        // an orderly quit, even one while the GPU device is still being created, is not a crash
        // inside the driver: the next launch keeps the GPU on
        lcc_engine::gpu::backend::release_init_marker_on_quit();
        // macOS only: the process ends below without running destructors, and only the lock's
        // `Drop` removes `catalog.lock.owner` (the OS frees the lock, not the note), so let go of
        // the library's lock here, saved or not (we leave either way). Elsewhere eframe drops the
        // app after this and the session's last writes (face data) still go out under the lock.
        #[cfg(target_os = "macos")]
        self.0.session.release_library_lock();
        // macOS (#1331): end the process here, before eframe tears the window down, as Quit from
        // the menu bar already does (PR #444). AccessKit's macOS adapter subclasses the window's
        // content view and restores its class on teardown; AppKit's Touch Bar support observes
        // that view (KVO), so in the next display cycle `-[_NSTouchBarFinderObservation
        // invalidate]` throws "not registered" and closing the window ends in a crash report.
        // Nothing after this is needed: settings and library are saved, background work has
        // stopped and the log file is unbuffered. `on_exit` only runs once the app exists, so a
        // renderer that fails to start still relaunches on the next one (`window_gpu`).
        #[cfg(target_os = "macos")]
        std::process::exit(0);
    }
}

/// How long quitting waits for renders that are running (issue #620). A GPU render takes well under
/// a second; anything slower gives way to quitting.
const EXIT_WAIT: std::time::Duration = std::time::Duration::from_secs(2);

