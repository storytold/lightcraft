/// The launch arguments' files and folders to import (absolute), and a notice for each one that
/// is not imported (see [`lcc_engine::import::launch_path`]; issue #374).
fn launch_imports(args: &[String]) -> LaunchArgs {
    let cwd = std::env::current_dir().ok();
    let home = std::env::var_os(if cfg!(windows) { "USERPROFILE" } else { "HOME" }).filter(|h| !h.is_empty()).map(std::path::PathBuf::from);
    launch_imports_in(args, cwd.as_deref(), home.as_deref())
}

/// What the launch arguments ask for: files and folders to import, a library to open (a library's `catalog.snap`
/// or folder, double-clicked in the file manager), and a notice for each argument
/// left alone.
#[derive(Debug, Default, PartialEq)]
struct LaunchArgs {
    files: Vec<String>,
    library: Option<std::path::PathBuf>,
    notices: Vec<String>,
}

fn launch_imports_in(args: &[String], cwd: Option<&std::path::Path>, home: Option<&std::path::Path>) -> LaunchArgs {
    use lcc_engine::import::{LaunchPath, launch_path};
    let (mut files, mut notices, mut library) = (Vec::new(), Vec::new(), None);
    for a in args {
        match launch_path(a, cwd, home, lcc_engine::devices::dcim_in) {
            Some(LaunchPath::Library(dir)) if library.is_none() => library = Some(std::path::PathBuf::from(dir)),
            Some(LaunchPath::Library(dir)) => {
                log::warn!("one library at a time: not opening {dir} given at launch");
                notices
                    .push(lcc_brand::fill(&format!("{dir} was not opened: {{app}} opens one catalog at a time. Open it with File ▸ Open Catalog…")));
            }
            Some(LaunchPath::Import(p)) => files.push(p),
            Some(LaunchPath::Refused { path, why }) => {
                log::warn!("not importing {path} given at launch: {why}");
                notices
                    .push(format!("{path} was not imported: it is {why}. To import from it, choose a folder inside it with File ▸ Import Photos…"));
            }
            None => {}
        }
    }
    LaunchArgs { files, library, notices }
}

/// Where the log files live: `logs` in the settings folder, next to `ui.json` (see `logging`).
/// None with `<PREFIX>_NO_PREFS` (tests, scripts), so those runs don't rotate away the user's logs.
fn log_dir() -> Option<std::path::PathBuf> {
    if lcc_brand::env_is_set("NO_PREFS") {
        return None;
    }
    config_dir().map(|d| d.join("logs"))
}

/// The control port `value` names; a value that isn't a port is logged and ignored (`what` is
/// the option or variable it came from). Logged before the log file opens, so it is kept for it.
fn control_port_from(what: &str, value: Option<String>) -> Option<u16> {
    let value = value?;
    let port = value.trim().parse().ok();
    if port.is_none() {
        log::warn!("{what} {value:?} is not a port number; no control server");
    }
    port
}

/// The control channel's token for this run: `supplied` (`--control-token` or
/// `<PREFIX>_CONTROL_TOKEN`) when given, else 32 fresh bytes from the operating system's random
/// source. `Err` says why there is none (then there is no control server).
fn control_token(supplied: Option<String>) -> Result<String, String> {
    if let Some(token) = supplied {
        return control_auth::validate(&token);
    }
    let mut bytes = [0u8; control_auth::TOKEN_HEX_LEN / 2];
    getrandom::fill(&mut bytes).map_err(|e| format!("no random source for the control token: {e}"))?;
    Ok(control_auth::encode(&bytes))
}

/// Write the token where clients on this machine find it ([`control_auth::token_file`]).
fn publish_control_token(port: u16, token: &str, supplied: bool) {
    match control_auth::token_file(port).map(|path| (control_auth::write_token_file(&path, token), path)) {
        Some((Ok(()), path)) => log::info!("control token for port {port}: {}", path.display()),
        Some((Err(e), _)) if supplied => log::warn!("could not store the control token ({e}); clients need {}", control_auth::token_env()),
        None if supplied => log::info!("no settings folder; clients need {}", control_auth::token_env()),
        // Nowhere to put a fresh token: show it once on stderr (not in the log file).
        Some((Err(e), _)) => eprintln!("{}: could not store the control token ({e}); token: {token}", lcc_brand::BINARY),
        None => eprintln!("{}: no settings folder for the control token; token: {token}", lcc_brand::BINARY),
    }
}

/// The emergency crash log, `<binary>-panics.log` beside the other logs in the user's own settings
/// folder (an isolated profile's with `<PREFIX>_CONFIG_DIR`). Never the shared temp folder, where
/// another user on the machine could create the file first or point it at one of the user's files.
/// `None` (standard error only) where no logs are kept, and in a `--memory` session, which saves nothing (upstream
/// #2572). `args` are the program's arguments, read before they are parsed (the panic hook is installed first to catch
/// a panic while parsing); they are `OsString`s, so an argument that isn't UTF-8 can't panic here.
fn panic_log_path(args: impl IntoIterator<Item = std::ffi::OsString>) -> Option<std::path::PathBuf> {
    if in_memory_session(args) {
        return None;
    }
    log_dir().map(|d| d.join(format!("{}-panics.log", lcc_brand::BINARY)))
}

/// Whether the arguments ask for a `--memory` (or `--demo`) session. The values of `--control` and `--library` are
/// skipped, as the parser takes them.
/// Whether the window looks for a newer release at start: only a session that keeps its settings, and not when
/// `--no-update-check` was given (Settings > General still decides within that).
fn startup_update_check(keeps_settings: bool, no_update_check: bool) -> bool {
    keeps_settings && !no_update_check
}

fn in_memory_session(args: impl IntoIterator<Item = std::ffi::OsString>) -> bool {
    let mut args = args.into_iter();
    while let Some(a) = args.next() {
        if a == "--control" || a == "--library" {
            args.next();
        } else if a == "--memory" || a == "--demo" {
            return true;
        }
    }
    false
}

fn main() -> eframe::Result {
    // First, so every start-up record is kept for the log file (`logging`).
    let logger = logging::install();
    lcc_engine::guard::install_hook(panic_log_path(std::env::args_os().skip(1)));
    if let Some(logger) = logger {
        logging::record_panics(logger);
    }
    alloc_release::install();
    // the shared worker pool leaves cores free and renders run below normal priority
    threads::install();
    let mut control_port = control_port_from(&lcc_brand::env_var("CONTROL_PORT"), lcc_brand::env("CONTROL_PORT").filter(|v| !v.is_empty()));
    let mut control_token_arg = control_auth::env_token().filter(|v| !v.trim().is_empty());
    let mut files = Vec::new();
    let mut seed_demo = true;
    let mut no_update_check = false;
    let mut in_memory = false;
    let mut library_dir: Option<std::path::PathBuf> = None;
    let mut launch_link: Option<String> = None;
    // `std::env::args` panics on an argument that isn't UTF-8 (a file a file manager hands over, say):
    // read it lossily, so such a file is reported as not found instead
    let mut args = std::env::args_os().skip(1).map(|a| a.to_string_lossy().into_owned()).peekable();
    while let Some(a) = args.next() {
        match a.as_str() {
            "--control" => control_port = control_port_from("--control", Some(args.next().unwrap_or_default())),
            "--control-token" => control_token_arg = Some(args.next().unwrap_or_default()),
            "--library" => library_dir = args.next().map(std::path::PathBuf::from),
            "--no-demo" => seed_demo = false,
            "--no-update-check" => no_update_check = true,
            "--memory" | "--demo" => in_memory = true,
            "--hdr-probe" => {
                // optional seconds (default 5)
                let secs = args.next_if(|v| v.parse::<u64>().is_ok()).and_then(|v| v.parse().ok()).unwrap_or(5);
                return hdr_probe::run(secs, log_dir());
            }
            "--version" => {
                println!("{} {}", lcc_brand::BINARY, env!("CARGO_PKG_VERSION"));
                return Ok(());
            }
            "-h" | "--help" => {
                print!("{}", help());
                return Ok(());
            }
            o if o.starts_with("--") => {
                eprintln!("{}: unknown option `{o}`\n\n{}", lcc_brand::BINARY, help());
                std::process::exit(2);
            }
            // one of the app's links (`<scheme>://sync?path=…`): followed once the window is up
            l if lcc_engine::link::is_link(l) => launch_link = Some(a.clone()),
            _ => files.push(a),
        }
    }
    // first start under this name: copy the settings folder of a previous name (never moved). Before the
    // log file opens, which creates the new settings folder.
    if !in_memory && !lcc_brand::env_is_set("NO_PREFS") {
        match lcc_brand::migrate_legacy_settings() {
            Ok(Some(from)) => log::info!("settings copied from {}", from.display()),
            Ok(None) => {}
            Err(e) => log::warn!("could not copy the previous settings folder: {e}"),
        }
        // a settings folder that already existed: its control-surface layouts still come over
        migrate_legacy_surface_file();
    }
    // The log file: opened after the arguments, so `--version`, `--help` and a usage error leave
    // no file behind. Records logged until now are written to it first.
    let mut log_file = None;
    if let Some(logger) = logger {
        // a --memory session writes nothing (issue #164), a log file included
        match log_dir().filter(|_| !in_memory) {
            Some(dir) => match logger.attach_dir(&dir) {
                Ok(path) => {
                    log::info!("{} {}, log file {}", lcc_brand::DISPLAY_NAME, env!("CARGO_PKG_VERSION"), path.display());
                    log_file = Some(path);
                }
                // The file sink has given up by now, so this goes to standard error only.
                Err(e) => log::warn!("no log file: {e}"),
            },
            None => logger.no_file(),
        }
    }
    // a Windows copy unpacked from the zip, before anything is opened: a version a zip update
    // started waits here until the one it replaced has ended (however long quitting takes); a new
    // version that never came up on its last start is undone and the previous one started instead
    let after_update = match lcc_engine::update::on_start() {
        lcc_engine::update::Start::Undone(previous) => {
            log::warn!("this version did not come up after its update; {} was put back and started", previous.display());
            return Ok(());
        }
        lcc_engine::update::Start::AfterUpdate => true,
        lcc_engine::update::Start::Go => false,
    };
    // the start after an update: delete the previous AppImage, log a swap that failed (in the
    // background; the start never waits for it). Not in a run that keeps no settings (--memory,
    // <PREFIX>_NO_PREFS): its updater stages in the temp folder, not the settings folder's.
    if !in_memory && !lcc_brand::env_is_set("NO_PREFS") {
        lcc_engine::update::clean_up_after_update();
    }
    // what the arguments name, resolved now: an empty or relative argument never becomes a drive
    // root, and a whole drive or home folder is not walked (issue #374)
    let LaunchArgs { files, library: launch_library, notices: launch_notices } = launch_imports(&files);
    // a library double-clicked (its catalog.snap or folder) is the one that opens, not the last one used
    let opened_by_argument = launch_library.is_some() && library_dir.is_none();
    let library_dir = library_dir.or(launch_library);
    let (prefs, prefs_warning, keep_prefs_file) = load_prefs(in_memory);
    // the saved language from the start, so a failed start is reported in it too
    if let Some(ui) = &prefs {
        lcc_ui_egui::i18n::set_language(ui.language);
    }
    // --library (or <PREFIX>_LIBRARY), else the list of recent libraries if Settings say Ask me,
    // else the library last opened from Settings, else the default location if a library of this
    // app is there; otherwise (a first start) the welcome dialog asks. Another app's library (e.g.
    // the upstream app's, named by settings copied from it) is never opened as this app's own.
    let mut prefs = prefs;
    // the recent list of older versions joins the settings' before Ask me is read (issue #871)
    catalog_hooks::carry_over_recent(prefs.as_mut(), !in_memory && !keep_prefs_file, |ui| {
        PrefsWriter { path: prefs_path(), ..Default::default() }.save_ui(ui, false)
    });
    let explicit = library_dir.or_else(|| lcc_brand::env_os("LIBRARY").filter(|p| !p.is_empty()).map(Into::into));
    // only a library named on the command line or in the environment may be created at launch
    let explicit_given = explicit.is_some();
    let plan = lcc_ui_egui::panels::library_problem::launch_plan(in_memory, explicit.clone(), None, prefs.as_ref().map(|u| &u.settings), None);
    let (library_dir, welcome) = if in_memory || plan == Launch::Ask {
        (explicit, None)
    } else {
        let from_prefs = prefs.as_ref().map(|u| u.settings.library_path.clone()).filter(|p| !p.is_empty() && !lcc_brand::env_is_set("LIBRARY"));
        let remembered = [from_prefs.map(Into::into)];
        match catalog_hooks::decide(explicit, &remembered, lcc_engine::library::default_dir()) {
            catalog_hooks::Startup::Open(d) => (Some(d), None),
            catalog_hooks::Startup::Welcome { foreign } => {
                // another app's library is not remembered as this app's any more
                if let Some(u) = prefs.as_mut()
                    && catalog_hooks::is_foreign(std::path::Path::new(&u.settings.library_path))
                {
                    u.settings.library_path.clear();
                }
                (None, Some(foreign))
            }
        }
    };
    let launch = match plan {
        Launch::Ask => Launch::Ask,
        Launch::Open { alt_asks, .. } => Launch::Open { dir: library_dir.clone(), alt_asks: alt_asks && welcome.is_none() },
    };
    // relaunched by a zip update while a copy started by hand (the new version too) already has the
    // library open: that one is in use, so this one ends quietly instead of asking about the library
    if after_update
        && let Launch::Open { dir: Some(dir), .. } = &launch
        && lcc_engine::update::library_in_use(dir)
    {
        log::info!("{} is already open in another copy of the new version; this relaunch ends here", dir.display());
        lcc_engine::update::release_start();
        return Ok(());
    }
    // GPU compute: off if the preference says so, or if the last launch died creating the device
    // (issue #136) — before anything can create it
    let gpu_crash = gpu_crash_check(in_memory).or_else(|| gpu_lost_check_at(gpu_lost_marker_path().as_deref(), in_memory));
    if prefs.as_ref().is_some_and(|u| !u.settings.hdr_display) {
        hdr_display::switch_off();
    }
    let gpu_on = prefs.as_ref().is_none_or(|u| u.settings.gpu) && gpu_crash.is_none();
    lcc_engine::gpu::set_enabled(gpu_on);
    // batch work (exports, previews being built) leaves the editing card to the interface while it
    // is used, and goes to a second graphics card first
    lcc_engine::gpu::track_interaction(true);
    if let Some(u) = &prefs {
        lcc_engine::gpu::backend::set_compute_preference(u.settings.gpu_backend.name());
    }
    // the window's renderer: probed (Windows) and with a fallback chain, so a driver that can't
    // build egui's pipeline never kills the start-up
    let compose_window = prefs.as_ref().is_some_and(|ui| ui.settings.compose_window) && std::env::var_os("WGPU_BACKEND").is_none();
    let win_files = std::sync::Arc::new(window_files(in_memory));
    let window_gpu::Chosen { renderer, mut wgpu_options, which: window_renderer, notice: window_notice } =
        window_gpu::choose(&win_files, compose_window);
    // HDR display output: an extended-range float surface where the platform and display offer it
    hdr_display::configure(&mut wgpu_options);
    win_files.arm(window_renderer);
    let win_files_app = win_files.clone();
    // the window came up: a failure after this is the app stopping, not a start that failed
    let came_up = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
    let came_up_app = came_up.clone();
    // how the window was when the app was last used (checked: the settings file is a file)
    let opens_as = prefs.as_ref().and_then(|ui| ui.window).and_then(lcc_ui_egui::window_place::WindowPlace::checked);
    let options = eframe::NativeOptions {
        renderer,
        viewport: as_remembered(egui::ViewportBuilder::default().with_title(lcc_brand::DISPLAY_NAME), opens_as, MAXIMIZE_LATER)
            .with_min_inner_size(lcc_ui_egui::window_place::MIN_SIZE)
            .with_drag_and_drop(true)
            .with_transparent(window_gpu::composes_window(compose_window, window_renderer))
            .with_fullsize_content_view(true)
            .with_titlebar_shown(false)
            .with_title_shown(false)
            .with_icon(app_icon())
            // Wayland matches the window to the packaged `<APP_ID>.desktop` file by this id
            .with_app_id(APP_ID),
        wgpu_options,
        ..Default::default()
    };
    // the app's copy: `log_file` is still named in the message of a start that fails
    let app_log_file = log_file.clone();
    #[cfg(all(unix, not(target_os = "macos")))]
    let mut options = options;
    // winit has no file drag-and-drop on Wayland (only on X11), so dropping files from the file
    // manager showed a "no" cursor. Run through XWayland when it's there; <PREFIX>_WAYLAND=1
    // keeps the native Wayland backend.
    #[cfg(all(unix, not(target_os = "macos")))]
    // (an output with HDR headroom — the compositor says so — needs the native backend: XWayland
    // windows are SDR)
    if std::env::var_os("DISPLAY").is_some() && !lcc_brand::env_is_set("WAYLAND") && hdr_display::read_compositor_headroom().is_none() {
        options.event_loop_builder = Some(Box::new(|b| {
            use winit::platform::x11::EventLoopBuilderExtX11;
            b.with_x11();
        }));
    }
    let started = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        eframe::run_native(
            lcc_brand::DISPLAY_NAME,
            options,
            Box::new(move |cc| {
                // the window's renderer is up (eframe calls this after creating it)
                win_files_app.started(window_renderer);
                came_up_app.store(true, std::sync::atomic::Ordering::Relaxed);
                // an older catalog is upgraded on a worker thread once the window shows, with progress
                let upgrade = library_dir.clone().filter(|d| !in_memory && lcc_engine::library::needs_migration(d));
                // any other on-disk library opens there too: the open ran here, before the first
                // frame, where a store an update left in an older format (its byte-verified backup
                // copy) or simply a large one being read kept the window silent — as an import of a
                // large folder once did (issue #374)
                let deferred_open = upgrade.is_none() && welcome.is_none() && !in_memory && matches!(launch, Launch::Open { dir: Some(_), .. });
                let open_dir = match (&launch, deferred_open) {
                    (Launch::Open { dir: Some(d), .. }, true) => Some(d.clone()),
                    _ => None,
                };
                let (mut session, mut problem) = if upgrade.is_some() || welcome.is_some() {
                    (unopened_session(), None)
                } else if deferred_open {
                    // why it can't be opened at all, told now; the rest is the worker's to find
                    (unopened_session(), launch_problem(open_dir.as_ref(), explicit_given))
                } else {
                    open_session(in_memory, &launch, seed_demo && files.is_empty(), explicit_given)
                };
                // AI masks: the SAM 3 checkpoint (facebook/sam3) in <config>/models/sam3, or <PREFIX>_SAM3_DIR
                // (never required: without it, AI masks offer to download it; see docs/ai-masks.md)
                // and the user's own download locations, one base URL per line (<PREFIX>_SAM3_MIRRORS too)
                session = session.with_default_sam3_model();
                // automatic XMP writes don't hold up the edit that made them (on a network share a write is many round trips)
                session.set_background_sidecar_writes(true);
                // updates: a run that keeps no settings (--memory, <PREFIX>_NO_PREFS) neither reads
                // nor writes the settings folder's updates.json, and never checks at start
                let keeps_settings = !in_memory && !lcc_brand::env_is_set("NO_PREFS");
                if !keeps_settings {
                    session.updater = lcc_engine::update::Updater::new(None);
                }
                // HDR display: SDR unless the surface, platform and display all allow HDR
                let display = hdr_display::report(cc.wgpu_render_state.as_ref());
                let mut app = LccApp::new(session, services(cc, app_log_file.as_deref()));
                // the window and the app are up: a zip update that put this version here worked
                lcc_engine::update::confirm_update();
                app.hdr_display_sdr = !display.is_hdr();
                if let Some(ui) = prefs {
                    app.ui = ui;
                    // Auto Sync is the app's, remembered across libraries and restarts
                    app.session.auto_sync = app.ui.settings.auto_sync;
                }
                // the recent libraries to choose from (issue #1290), checked on a worker once shown
                if launch == Launch::Ask {
                    problem = Some(LibraryProblem::choose_later(&app.ui.settings));
                }
                app.alt_asks_for_library = matches!(launch, Launch::Open { alt_asks: true, .. });
                lcc_ui_egui::i18n::set_language(app.ui.language);
                app.integrated_titlebar = cfg!(target_os = "macos");
                app.notices.extend(prefs_warning);
                app.notices.extend(launch_notices);
                app.notices.extend(window_notice);
                app.pending_link = launch_link;
                app.gpu_notice = true;
                // the start-up update check, when the user turned it on (off by default)
                app.startup_update_check = startup_update_check(keeps_settings, no_update_check);
                // an empty library opens where Import is offered (a grid, with the sidebar); before
                // the snapshot below, so this alone isn't written to the settings file. One whose
                // open runs on a worker (a format upgrade, or the deferred open) is told after it
                // opens, so a library with photos keeps the view it was left in
                if problem.is_none() && files.is_empty() && upgrade.is_none() && open_dir.is_none() {
                    lcc_ui_egui::panels::empty_library::open_on_empty_library(&mut app);
                }
                // what's on disk now: only changes are written
                let writer = PrefsWriter {
                    path: if in_memory { None } else { prefs_path() },
                    written: serde_json::to_vec_pretty(&app.ui).unwrap_or_default(),
                    library: app.ui.settings.library_path.clone(),
                    keep_file: keep_prefs_file,
                    start: Some(lcc_ui_egui::window_place::StartPlace::new(MAXIMIZE_LATER && opens_as.is_some_and(|w| w.zoomed))),
                    ..Default::default()
                };
                // a library opened from its catalog file is the one in use from now on, as Open Library makes it
                // (after the snapshot above, so the writer saves it)
                if opened_by_argument
                    && problem.is_none()
                    && let Some(dir) = app.session.library.as_ref().filter(|l| l.on_disk).map(|l| l.dir.to_string_lossy().into_owned())
                {
                    let settings = &mut app.ui.settings;
                    if settings.library_path != dir && !settings.library_path.is_empty() {
                        let previous = settings.library_path.clone();
                        lcc_ui_egui::panels::settings::remember_library(&mut settings.recent_libraries, &previous);
                    }
                    lcc_ui_egui::panels::settings::remember_library(&mut settings.recent_libraries, &dir);
                    settings.library_path = dir;
                }
                // after the snapshot above, so the writer saves the switched-off preference
                if let Some(notice) = gpu_crash {
                    app.ui.settings.gpu = false;
                    app.notices.push(notice);
                }
                let (midi_actions, midi_reload, midi_problem) = midi::start(cc.egui_ctx.clone());
                app.notices.extend(midi_problem);
                app = app.with_midi(midi_actions, midi_reload);
                // requests from --control and from the control-surface listener
                let (control_tx, control_rx) = std::sync::mpsc::channel();
                let mut control_started = false;
                if let Some(port) = control_port {
                    let supplied = control_token_arg.is_some();
                    match control_token(control_token_arg) {
                        Ok(token) => {
                            // bind first: the token file is written only once the port is ours
                            let publish = |token: &str| publish_control_token(port, token, supplied);
                            control_started = control_server::start(port, token, control_tx.clone(), cc.egui_ctx.clone(), publish);
                        }
                        Err(e) => log::error!("no control server: {e}"),
                    }
                }
                app = if control_started { app.with_control(control_rx) } else { app.with_requests(control_rx) };
                let listener_ctx = cc.egui_ctx.clone();
                let mut running: Option<std::sync::Arc<std::sync::atomic::AtomicBool>> = None;
                app.services.surface_listener = Some(Box::new(move |port: Option<u16>| {
                    if let Some(stop) = running.take() {
                        stop.store(true, std::sync::atomic::Ordering::SeqCst);
                    }
                    if let Some(port) = port {
                        running = Some(control_server::start_surfaces(port, control_tx.clone(), listener_ctx.clone())?.0);
                    }
                    Ok(())
                }));
                if let Some(foreign) = welcome {
                    // a first start: create a catalog or open one (command-line files wait for it)
                    lcc_ui_egui::catalog_ui::welcome(&mut app, foreign.iter().map(|p| p.display().to_string()).collect());
                    app.catalog_ui.pending_import = files;
                } else if let Some(dir) = upgrade {
                    lcc_ui_egui::panels::library_problem::start_upgrade(&mut app, dir, files);
                } else if let Some(dir) = open_dir.filter(|_| problem.is_none()) {
                    // the catalog opens on the worker once the window shows: "Opening your
                    // catalog", with the progress of a format upgrade on the way. Files from the
                    // command line wait for it, as behind the upgrade window
                    let demo = seed_demo && files.is_empty();
                    lcc_ui_egui::panels::library_problem::start_open(&mut app, dir, files, demo, opened_by_argument);
                } else if let Some(mut p) = problem {
                    // imported once the user has chosen where (into the library, or the temporary session)
                    p.pending_import = files;
                    app.library_problem = Some(p);
                } else if !files.is_empty() {
                    // listed and read on the import worker once the window shows (issue #374: never
                    // here, before the first frame, where a large folder kept the window from
                    // appearing)
                    if let Err(e) = lcc_ui_egui::import::start_paths(&mut app, files) {
                        log::warn!("import at launch: {e}");
                    }
                    app.ui.view = lcc_ui_egui::state::ViewMode::PhotoGrid;
                }
                // native menu bar generated from the command registry (macOS; elsewhere the menus are
                // drawn in the window's top bar). <PREFIX>_NO_NATIVE_MENU=1 keeps the in-window menus.
                #[cfg(target_os = "macos")]
                let menu = (!lcc_brand::env_is_set("NO_NATIVE_MENU")).then(|| native_menu::NativeMenu::install(&mut app, &cc.egui_ctx));
                // the GPU renderer on the window's device, when GPU rendering is on
                // (<PREFIX>_GPU_WINDOW=0: a device of its own, renders read back - for comparison or a
                // driver that misbehaves with compute and drawing on one device)
                // Not on an HDR window under Linux / BSD for now: with the renderer on the window's
                // device, turning an edit's HDR on stopped the Wayland window drawing (RADV,
                // 2026-11-03; fine with a device of its own). `<PREFIX>_GPU_WINDOW=1` offers it
                // anyway, `0` never.
                let window_device = offers_window_device(lcc_brand::env("GPU_WINDOW").as_deref(), display.is_hdr(), HDR_WINDOW_GUARD);
                let window_textures = cc.wgpu_render_state.as_ref().filter(|_| gpu_on && window_device).map(offer_window_device);
                Ok(Box::new(App(
                    app,
                    writer,
                    window_textures,
                    #[cfg(target_os = "macos")]
                    menu,
                )))
            }),
        )
    }));
    if came_up.load(std::sync::atomic::Ordering::Relaxed) {
        // the window was up: a panic that escaped it now is the app stopping, typically the
        // window's renderer after the graphics driver reset the GPU (issue #1337: egui-wgpu panics
        // on the lost device). Not a failed start: no other renderer is tried, and the message
        // says what happened.
        let stopped = match started {
            Ok(r) => r,
            Err(_) => Err(eframe::Error::AppCreation("its window stopped drawing (the renderer panicked)".into())),
        };
        if let Err(e) = &stopped {
            let lost = gpu_lost_reason();
            if let Some(reason) = &lost
                && !in_memory
            {
                record_gpu_lost(gpu_lost_marker_path().as_deref(), reason);
            }
            // (not "app creation error: …": the app had been created)
            let what = match e {
                eframe::Error::AppCreation(m) => m.to_string(),
                e => e.to_string(),
            };
            stopped_while_running(&stopped_text(&what, lost.as_deref()), log_file.as_deref());
        }
        return stopped;
    }
    // a panic that still escaped the renderer's start (the probe and error handler should
    // prevent it): an error like any other failed start
    let started = started.unwrap_or_else(|_| Err(eframe::Error::AppCreation("the window's renderer panicked while starting".into())));
    if let Err(e) = &started {
        // the renderer never came up: start again, which tries the next one in the chain
        if window_gpu::relaunch_after_failure(&win_files) {
            log::error!("{} could not open its window with {}: {e}; trying the next renderer", lcc_brand::DISPLAY_NAME, window_renderer.name());
            return Ok(());
        }
        startup_failed(&e.to_string(), log_file.as_deref());
    }
    started
}

/// What to tell the user when the app stopped while running (`error`), and why when the GPU
/// was lost (`lost`): GPU rendering is off from the next start.
fn stopped_text(error: &str, lost: Option<&str>) -> String {
    match lost {
        Some(reason) => format!(
            "{error}. The graphics driver reset the GPU ({reason}). {app} renders on the CPU from its next start; \
             Settings ▸ Performance ▸ Use the GPU for rendering turns the GPU back on",
            app = lcc_brand::DISPLAY_NAME
        ),
        None => error.to_string(),
    }
}

/// The app stopped while its window was up: say so in the log and in a native message box
/// naming the log file (as [`startup_failed`] does for a start that failed).
fn stopped_while_running(text: &str, log_file: Option<&std::path::Path>) {
    log::error!("{} stopped: {text}", lcc_brand::DISPLAY_NAME);
    if lcc_brand::env_is_set("NO_PREFS") {
        return; // tests and scripts: no dialog to click away
    }
    let (title, text) = lcc_ui_egui::i18n::stopped_message(text, log_file.map(|p| p.display().to_string()).as_deref());
    let _ = rfd::MessageDialog::new()
        .set_level(rfd::MessageLevel::Error)
        .set_title(title)
        .set_description(text)
        .set_buttons(rfd::MessageButtons::Ok)
        .show();
}

/// The window could not start (e.g. no usable graphics device): say so in the log and in a native
/// message box naming the log file, instead of exiting without a trace — the release builds have
/// no console on Windows, and an app started from Finder shows no standard error (issue #260).
fn startup_failed(error: &str, log_file: Option<&std::path::Path>) {
    log::error!("{} could not open its window: {error}", lcc_brand::DISPLAY_NAME);
    if lcc_brand::env_is_set("NO_PREFS") {
        return; // tests and scripts: no dialog to click away
    }
    let (title, text) = lcc_ui_egui::i18n::startup_failed_message(error, log_file.map(|p| p.display().to_string()).as_deref());
    let _ = rfd::MessageDialog::new()
        .set_level(rfd::MessageLevel::Error)
        .set_title(title)
        .set_description(text)
        .set_buttons(rfd::MessageButtons::Ok)
        .show();
}

